export type AgentRegistryEntry = {
  /** Stable UI / routing id */
  id: string;
  displayName: string;
  roleTitle: string;
  department: AgentDepartment;
  responsibility: string;
  trigger: AgentTrigger;
  /** Dashboard module key */
  module: string;
  /** Primary code path that executes this agent */
  executionPath: string;
  /** Inngest function id when scheduled/event-driven */
  inngestId?: string;
  /**
   * Values written to agent_runs.agent_name for this agent.
   * Empty when the job does not yet persist runs (still a real executor).
   */
  agentNames: string[];
  /** Show Run now when defined; handler in lib/team/run-actions.ts */
  runNow?: {
    kind: AgentRunNowKind;
    requiresBrand?: boolean;
    /** Meeting / report type payload */
    type?: string;
  };
  /** Default deep link when a run has no entity id */
  moduleHref: string;
};

