export function getAgentById(id: string): AgentRegistryEntry | undefined {
  return AGENT_REGISTRY.find((a) => a.id === id);
}

export function getAgentsByDepartment(
  department: AgentDepartment,
): AgentRegistryEntry[] {
  return AGENT_REGISTRY.filter((a) => a.department === department);
}

export function isAgentDepartment(value: string): value is AgentDepartment {
  return (AGENT_DEPARTMENTS as readonly string[]).includes(value);
}

/** All agent_names used for live agent_runs queries for an entry. */
export function agentNamesForEntry(entry: AgentRegistryEntry): string[] {
  return entry.agentNames;
}

/** Reverse lookup: agent_runs.agent_name → registry entries */
export function entriesForAgentName(agentName: string): AgentRegistryEntry[] {
  return AGENT_REGISTRY.filter((e) => e.agentNames.includes(agentName));
}
